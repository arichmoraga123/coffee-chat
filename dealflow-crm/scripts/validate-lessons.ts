/**
 * Validates every lesson in content/lessons/ and regenerates src/lib/learn/lessons.generated.ts.
 * Runs before every build (prebuild), so a malformed lesson fails the build instead of a page.
 * Usage: npm run validate-lessons
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { LessonSchema } from "../src/lib/learn/schema";

const root = process.cwd();
const dir = path.join(root, "content/lessons");
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const errors: string[] = [];
const ids = new Map<string, string>();
const lessons: { id: string; file: string; prerequisites: string[] }[] = [];

for (const file of files) {
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
  } catch (e) {
    errors.push(`${file}: invalid JSON — ${(e as Error).message}`);
    continue;
  }
  const parsed = LessonSchema.safeParse(raw);
  if (!parsed.success) {
    for (const issue of parsed.error.issues) errors.push(`${file}: ${issue.path.join(".")} — ${issue.message}`);
    continue;
  }
  const l = parsed.data;
  const expected = `${l.id}-${l.slug}.json`;
  if (file !== expected) errors.push(`${file}: file name should be ${expected}`);
  if (ids.has(l.id)) errors.push(`${file}: duplicate lesson id ${l.id} (also in ${ids.get(l.id)})`);
  ids.set(l.id, file);
  lessons.push({ id: l.id, file, prerequisites: l.prerequisites });
}

for (const l of lessons) {
  for (const p of l.prerequisites) if (!ids.has(p)) errors.push(`${l.file}: prerequisite ${p} does not exist`);
}

if (errors.length) {
  console.error(`✗ ${errors.length} lesson problem(s):\n  ${errors.join("\n  ")}`);
  process.exit(1);
}

const sortKey = (id: string) => id.split("-").map(Number);
lessons.sort((a, b) => {
  const [am, al] = sortKey(a.id);
  const [bm, bl] = sortKey(b.id);
  return am - bm || al - bl;
});
const out = [
  "// AUTO-GENERATED by scripts/validate-lessons.ts — do not edit. Run `npm run validate-lessons`.",
  ...lessons.map((l, i) => `import l${i} from "../../../content/lessons/${l.file}";`),
  "",
  `export const RAW_LESSONS: unknown[] = [${lessons.map((_, i) => `l${i}`).join(", ")}];`,
  "",
].join("\n");
writeFileSync(path.join(root, "src/lib/learn/lessons.generated.ts"), out);
console.log(`✓ ${lessons.length} lesson(s) valid`);
